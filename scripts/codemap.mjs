// Generates CODEMAP.md: a token-cheap index of the code, so a session (person or AI) can jump straight
// to the lines it needs instead of reading whole files.
//
//   npm run codemap          rewrite CODEMAP.md
//   npm run codemap -- --check   exit 1 if CODEMAP.md is stale (used by `npm test`)
//
// Everything below "Where to change what" is generated from the source: section banners
// (`// ====` blocks) and top-level functions with their line numbers.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(new URL('..', import.meta.url).pathname);
const OUT = join(ROOT, 'CODEMAP.md');

// Hand-written: the tasks people actually do, and where they start. Keep it short.
const TASKS = [
  ['Add or rebalance a perk / combo / Masterwork', '`src/upgrades.js` `UPGRADES` (+ `GAIN` line if a new stat) · test in `test/game-logic.test.js`'],
  ['Tune story difficulty or rewards', '`src/story.js` `difficulty()`, `roomReward()` · the "harder every room / wing" tests must pass'],
  ['Add or change a story wing', '`src/story.js` `WINGS` (enemy mix, density, floor, rug)'],
  ['Add or reprice a Renovation', '`src/meta.js` `RENOVATIONS` (+ `runBonuses()` if it is not a stat)'],
  ['Endless wave pacing', '`src/waves.js` `ENEMY_TYPES`, `waveBudget()`, `composeWave()`'],
  ['New enemy type', '`src/waves.js` `ENEMY_TYPES` → `main.js` `DEF`, `updateEnemies()` switch, `drawEnemy()`, `killEnemy()` colours'],
  ['Boss behaviour', '`main.js` `bossAI()` (tiers come from `difficulty().bossTier`)'],
  ['Player feel (move, dash, fire)', '`main.js` `updatePlayer()`, `fire()`, `spawnBook()`'],
  ['A menu / screen', '`index.html` `<section id=…>` + `main.js` `SCREENS`, the `data-act` click handler, `render*()` for that screen · CSS in `src/game.css` (scope tokens to the component)'],
  ['HUD', '`main.js` `drawHUD()`'],
  ['Saved data', '`main.js` keys `overdue.*.v1` · progression in `src/meta.js` `normalizeProgress()` (never reshape without a migration)'],
  ['Debug / test hooks', '`main.js` `window.__overdue` (bottom) · used by `scripts/qa/run.mjs`'],
  ['QA checks', '`scripts/qa/run.mjs` (screens per device, perf, privacy)'],
];

const files = ['index.html', ...readdirSync(join(ROOT, 'src')).filter((f) => f.endsWith('.js')).sort().map((f) => `src/${f}`),
  ...readdirSync(join(ROOT, 'test')).filter((f) => f.endsWith('.js')).sort().map((f) => `test/${f}`),
  ...['scripts/qa/run.mjs', 'scripts/build.mjs', 'scripts/serve.mjs', 'scripts/codemap.mjs'].filter((f) => existsSync(join(ROOT, f)))];

const FN = /^(?:export\s+)?(?:async\s+)?function\s+(\w+)|^(?:export\s+)?(?:const|let)\s+([A-Z_][A-Z0-9_]*|\w+)\s*=\s*(?:\(|async\s*\(|\w+\s*=>|new\s|\[|\{)/;

function purpose(lines) {
  const l = lines.find((x) => x.startsWith('//'));
  return l ? l.replace(/^\/\/\s*/, '').replace(/\|/g, '/') : '';
}

function mapFile(rel) {
  const lines = readFileSync(join(ROOT, rel), 'utf8').split('\n');
  const n = lines.length;
  if (rel.endsWith('.html')) {
    const ids = [];
    lines.forEach((l, i) => { const m = l.match(/<section id="(\w+)"/); if (m) ids.push(`${m[1]}:${i + 1}`); });
    return { rel, n, about: 'Page shell: menus and screens as `<section id>`', body: ids.length ? `Screens: ${ids.join(' · ')}` : '' };
  }
  // Section banners: "// =====" line, then a "// Title" line.
  const sections = [];
  lines.forEach((l, i) => {
    if (/^\/\/ ={5,}/.test(l) && /^\/\/ \w/.test(lines[i + 1] || '')) sections.push({ title: lines[i + 1].slice(3).trim(), line: i + 1 });
  });
  const defs = [];
  lines.forEach((l, i) => {
    if (rel.startsWith('test/')) { const t = l.match(/^test\('([^']+)'/); if (t) defs.push({ name: t[1], line: i + 1, test: true }); return; }
    const m = l.match(FN);
    if (m) defs.push({ name: m[1] || m[2], line: i + 1 });
  });
  let body = '';
  if (sections.length) {
    body = sections.map((s, k) => {
      const end = (sections[k + 1]?.line ?? n + 1) - 1;
      const inside = defs.filter((d) => d.line >= s.line && d.line <= end).map((d) => `${d.name}:${d.line}`);
      return `- **${s.title}** (${s.line}–${end}): ${inside.join(' · ')}`;
    }).join('\n');
  } else if (defs.length) {
    body = defs.some((d) => d.test) ? defs.map((d) => `- ${d.line}: ${d.name}`).join('\n') : defs.map((d) => `${d.name}:${d.line}`).join(' · ');
  }
  return { rel, n, about: purpose(lines), body };
}

function generate() {
  const maps = files.map(mapFile);
  const out = [
    '# Code map',
    '',
    '<!-- Generated by `npm run codemap` from the source. Do not edit by hand except the task table in scripts/codemap.mjs. -->',
    '',
    '**How to use it (saves tokens):** find the function here, then read only those lines',
    '(e.g. `Read src/main.js offset 640 limit 60`, or `grep -n "function bossAI" src/main.js`). Don\'t read `main.js` whole.',
    'Line numbers are `name:line`. `npm test` fails if this file is stale; run `npm run codemap` after editing code.',
    '',
    '## Where to change what',
    '',
    '| Task | Start here |',
    '|---|---|',
    ...TASKS.map(([a, b]) => `| ${a} | ${b} |`),
    '',
    '## Files',
    '',
    '| File | Lines | What it is |',
    '|---|---|---|',
    ...maps.map((m) => `| \`${m.rel}\` | ${m.n} | ${m.about} |`),
    '',
    ...maps.filter((m) => m.body).flatMap((m) => [`## ${m.rel}`, '', m.body, '']),
  ].join('\n');
  return out;
}

const text = generate();
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('CODEMAP.md is stale: run `npm run codemap`'); process.exit(1); }
  console.log('CODEMAP.md is up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote CODEMAP.md (${text.length} chars, ~${Math.round(text.length / 4)} tokens)`);
}
